"""Shared task-runner foundation for KIS, QA, and TRAKE prediction.

This module holds the small amount of logic every task runner previously
duplicated:

- query-text-field resolution (``query_text_vi`` / ``query_text_en``);
- the embedding-space compatibility gate between encoder and index;
- frame-level search under strict mode or the explicit legacy-mismatch
  override;
- run-id / timestamp helpers for artifact provenance.

It is deliberately concrete: no pipeline framework, no registries. Task
modules keep their own ranking, evidence shaping, and artifact contracts.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Literal

import numpy as np

from aic2026.embeddings import EmbeddingSpace, validate_query_compatibility
from aic2026.index_artifact import IndexManifest
from aic2026.retrieval import IndexRetriever, RetrievalCandidate

QueryTextField = Literal["query_text_vi", "query_text_en"]

QUERY_TEXT_FIELDS = ("query_text_vi", "query_text_en")


def validate_query_text_field(field: str) -> None:
    """Validate one query text field name.

    Expected input:
        - field: candidate field name.

    Returns:
        - None.

    Raises:
        - ValueError: if the field is not a supported query text column.
    """
    if field not in QUERY_TEXT_FIELDS:
        raise ValueError(f"query_text_field must be one of {QUERY_TEXT_FIELDS}, got {field!r}")


def resolve_query_text_field(
    query_text_vi: str,
    query_text_en: str | None,
    field: QueryTextField,
) -> str:
    """Select and validate one query text field from a canonical query.

    Expected input:
        - query_text_vi: required Vietnamese query text.
        - query_text_en: optional English query text.
        - field: which text to resolve.

    Returns:
        - The resolved query text (never empty).

    Raises:
        - ValueError: if ``query_text_en`` was requested but is missing.
    """
    if field == "query_text_vi":
        return query_text_vi
    if query_text_en is None:
        raise ValueError("query_text_en was requested but is missing for at least one query")
    return query_text_en


def require_compatible_spaces(model_space: EmbeddingSpace, manifest: IndexManifest) -> None:
    """Require model/index embedding spaces to be compatible.

    Uses :meth:`EmbeddingSpace.is_compatible_with`: build-environment-only
    ``model_version`` differences are ignored, while every
    comparison-relevant field must match.

    Expected input:
        - model_space: the encoder's declared embedding space.
        - manifest: the index artifact manifest.

    Returns:
        - None.

    Raises:
        - ValueError: if the index has no embedding-space metadata or the
          spaces are incompatible.
    """
    index_space = manifest.embedding_space
    if index_space is None:
        raise ValueError("index artifact is missing embedding-space metadata")
    if not model_space.is_compatible_with(index_space):
        raise ValueError(
            "incompatible embedding spaces between encoder and index: "
            f"model {model_space.space_id!r} ({model_space.backend}/{model_space.model_id}) != "
            f"index {index_space.space_id!r} ({index_space.backend}/{index_space.model_id})"
        )


def search_candidates(
    retriever: IndexRetriever,
    query_embedding: Any,
    top_k: int,
    allow_mismatch: bool = False,
) -> list[RetrievalCandidate]:
    """Run frame-level retrieval under strict mode or explicit mismatch override.

    Expected input:
        - retriever: loaded index retriever.
        - query_embedding: text embedding generated by the encoder.
        - top_k: retrieval cutoff.
        - allow_mismatch: explicit legacy-index override gate; when set and
          the spaces mismatch, raw vectors may only be sent to indexes whose
          recorded backend is ``"legacy"``.

    Returns:
        - Ranked retrieval candidates.

    Raises:
        - ValueError: for incompatible spaces under strict mode, or when an
          override is requested for a non-legacy index that cannot accept
          raw vectors by contract.
    """
    if not allow_mismatch:
        validate_query_compatibility(query_embedding, retriever.manifest.embedding_space)
        return retriever.search(query_embedding, top_k=top_k)

    if query_embedding.space.is_compatible_with(retriever.manifest.embedding_space):
        return retriever.search(query_embedding, top_k=top_k)

    index_space = retriever.manifest.embedding_space
    if index_space is None:
        raise ValueError("index artifact is missing embedding-space metadata")
    if index_space.backend != "legacy":
        raise ValueError(
            "embedding-space mismatch override is only supported for legacy indexes; "
            f"index backend is {index_space.backend!r}"
        )
    return retriever.search(np.asarray(query_embedding.vector), top_k=top_k)


def utc_now_iso() -> str:
    """Return an ISO-8601 UTC timestamp with explicit Z suffix."""
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def portable_source_path(path: Path | str, *, root: Path | str | None = None) -> str:
    """Return a portable, machine-independent provenance string for a path.

    Provenance recorded in prediction artifacts must not embed absolute
    machine-specific locations. When ``path`` lies inside the repository
    root (or the explicit ``root``), the repo-relative POSIX path is
    recorded; otherwise only the final path component survives.

    Expected input:
        - path: query-source or index-artifact location.
        - root: optional repository root override (tests); defaults to
          :func:`aic2026.config.project_root`.

    Returns:
        - A relative POSIX path when possible, else the path's name.

    Raises:
        - No exceptions.
    """
    if root is None:
        from aic2026.config import project_root

        base = project_root()
    else:
        base = Path(root)
    try:
        return Path(path).resolve().relative_to(base.resolve()).as_posix()
    except (ValueError, OSError):
        return Path(path).name


def default_run_id(prefix: str) -> str:
    """Return a timestamped default run id for artifact provenance.

    Expected input:
        - prefix: task-specific id prefix (e.g. ``"kis"``, ``"btc-qa"``).

    Returns:
        - Run id of the form ``<prefix>-run-<UTC timestamp>``.

    Raises:
        - No exceptions.
    """
    return f"{prefix}-run-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}"
